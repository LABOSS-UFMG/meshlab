# -------------------------------------------------------------------------------- #
import numpy as np

# -------------------------------------------------------------------------------- #
class Group():

    def __init__(
            self,
            name: str,
            capacity: int,
        ) -> None:
        # ------------------------------------------------------------------------ #
        self.name = name

        # ------------------------------------------------------------------------ #
        self.indices = np.empty(capacity, dtype=np.int32)

        # ------------------------------------------------------------------------ #
        self.num_indices: int = 0

        # ------------------------------------------------------------------------ #
        return None

    def add_index(self, index: int) -> None:
        # ------------------------------------------------------------------------ #
        self.indices[self.num_indices] = index

        self.num_indices += 1

        # ------------------------------------------------------------------------ #
        return None

# -------------------------------------------------------------------------------- #
